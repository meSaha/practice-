# Variable: Values stored in memory.Variables act as containers that hold data of different types,
# such as numbers,strings ,lists ,or more complex objects.
integer = 120
print(integer)

floating = 10.2
print(floating)

string = "Python Programming"
print(string)

# Casting: Casting, also known as type conversion, is a process that converts a variable's
# data type into another data type.
integer = 120
print(type(integer))

floating = 10.2
print(type(floating))

string = "Python Programming"
print(type(string))

# small Integer program
a = int (12)
print("a will be:", a)

b = int(12.8)
print("b will be:", b)

c = int("31")
print("c will be:", c)


# small floating program
a = float(10)
print("Result is:", a)

b = float(12.8)
print("Result is :", b)

c = float("31")
print("Result is:", c)

d = float("14.2")
print("Result is:", d)


